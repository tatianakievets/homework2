print("Калькулятор индекса массы тела")
print("------------------------------")

height = float(input("Введите рост (в метрах): "))
weight = float(input("Введите вес (кг): "))

bmi = weight / (height ** 2)

print(f"\nВаш ИМТ: {bmi:.2f}")

if bmi < 18.5:
    print("Недостаточный вес")
    print("Рекомендуется увеличить калорийность питания")
elif bmi < 25:
    print("Нормальный вес")
    print("Продолжайте поддерживать здоровый образ жизни")
elif bmi < 30:
    print("Избыточный вес")
    print("Рекомендуется обратить внимание на питание и физическую активность")
else:
    print("Ожирение")
    print("Рекомендуется обратиться к врачу")